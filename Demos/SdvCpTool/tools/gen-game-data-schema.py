#!/usr/bin/env python3
"""从游戏源码生成 `GameDataSchema`：**资产 → 元素类**，以及**类 → 字段 → 容器种类**。

两个权威来源（都只读）：
  1. `D:\\sdv_src\\StardewValley\\DataLoader.cs` —— `Load<泛型>(content, "Data\\\\X")`，
     给出**资产名 → 元素类型**的映射。这是游戏自己说的，不是我们猜的。
  2. `D:\\sdv_gd\\**\\*.cs` —— `StardewValley.GameData.*` 的模型类，给出**类型 → 字段 → 字段类型**。

为什么要这张表：转换器必须知道「`Fish` 是 `List`、`FishAreas` 是 `Dictionary`」这类事实，
才能查出「数组被写成了对象」这类静默退化。拿原版数据反推形状噪音太大（实测 9145 处假阳性），
**只有模型能给出真类型**。

★ **为什么是两张表而不是一张**：只到「资产元素 → 一层字段」**够不着嵌套层**。
  实测 SVE 的 `Data/Buildings` 有 6 处 `DrawLayers[].DrawPosition` 被写成字符串
  （`"28, 116"`），回包直接失败，而一层表看不见它。
  所以按**类**建表（而不是按资产），字段再带上**元素类名** —— 校验器就能沿类型图逐层下钻。

★ **只收"从资产元素出发 6 层内够得着"的类**：全量模型类有几百个，收进来只会让表变大，
  而校验器根本走不到。

用法：
    python tools/gen-game-data-schema.py            # 生成并写回仓库
    python tools/gen-game-data-schema.py --check    # 只校验是否与仓库里的一致
"""
import os
import re
import sys

SRC = r'D:\sdv_src\StardewValley\DataLoader.cs'
GD = r'D:\sdv_gd'

# 声明为这些类型的标量字段 ⇒ **整数值不能写成小数记号**（见 `IntegerFields`）。
INTEGER_TYPES = {'byte', 'sbyte', 'short', 'ushort', 'int', 'uint', 'long', 'ulong'}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   '..', 'src', 'SdvCpTool.Core', 'Validating', 'GameDataSchema.cs')

HEADER = '''// <auto-generated>
//   由 tools/gen-game-data-schema.py 生成 —— **不要手改**。
//   数据来源：D:\\sdv_src\\StardewValley\\DataLoader.cs（资产→元素类型）
//            与 D:\\sdv_gd（StardewValley.GameData.* 的模型类字段）。
//   重新生成：python tools/gen-game-data-schema.py
// </auto-generated>

namespace SdvCpTool.Core.Validating;

/// <summary>字段在数据里应有的**容器种类**（JSON 层面只有这几种）。</summary>
public enum FieldKind
{
    /// <summary>标量（字符串 / 数字 / 布尔）。</summary>
    Scalar,

    /// <summary><c>List&lt;T&gt;</c> —— JSON 数组。</summary>
    Array,

    /// <summary><c>Dictionary&lt;K,V&gt;</c> —— JSON 对象。</summary>
    Map,

    /// <summary>
    /// <b>结构化标量</b>（<c>Vector2</c>/<c>Vector3</c>/<c>Rectangle</c>）—— JSON 里必须写成**对象**。
    /// 写成字符串（如 <c>"28, 116"</c>）打包器直接报
    /// <c>Error converting value "28, 116" to type 'Vector2'</c> ⇒ 该资产**打不出 XNB**。
    /// </summary>
    Struct,
}

/// <summary>
/// 一个字段的**类型引用**：容器种类 + 类型名（没有就空串）。
/// <para>
/// <c>Array</c>/<c>Map</c> 的 <see cref="ElementType"/> 是**元素类名**，是**下钻**用的：
/// <c>DrawLayers</c>（<c>Array</c>）的元素类是 <c>BuildingDrawLayer</c>，
/// 于是校验器能进去查它自己的字段。
/// </para>
/// <para>
/// <c>Struct</c> 的 <see cref="ElementType"/> 是**结构类型名**
/// （<c>Vector2</c>/<c>Vector3</c>/<c>Rectangle</c>）—— 「<c>"0, -32"</c> 该拆成哪几个分量」
/// 由它决定（见 <c>ValueDialectCoercion</c>）。
/// </para>
/// </summary>
public readonly record struct FieldRef(FieldKind Kind, string ElementType);

'''


def strip_generic(t: str) -> str:
    """去掉泛型实参，留下裸类名。"""
    t = t.strip()
    t = re.sub(r'<.*>', '', t)
    return t.split('.')[-1]


def split_top_level(s: str) -> list:
    """按顶层逗号切分泛型实参。"""
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '<':
            depth += 1
        elif ch == '>':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
            continue
        cur += ch
    if cur.strip():
        out.append(cur)
    return out


# 收得**窄**：只收我们核实过「原版写成 JSON 对象」的那几个。
# 例：Data/Buildings 的 DrawLayers[].DrawPosition（Vector2）原版写 {"X":32.0,"Y":96.0}。
# 不收 Color —— 它在数据里可能是字符串（"Red" / "255, 0, 0"），未确证，收进来会误报。
STRUCT_TYPES = {'Vector2', 'Vector3', 'Rectangle'}


def container_of(type_text: str) -> str:
    """字段类型 → 容器种类。"""
    t = type_text.strip().rstrip('?')
    if t.startswith('List<') or re.match(r'^[A-Za-z0-9_.]+\[\]$', t):
        return 'Array'
    if t.startswith('Dictionary<'):
        return 'Map'
    if strip_generic(t) in STRUCT_TYPES:
        return 'Struct'
    return 'Scalar'


def bare_class(t: str):
    """类型文本 → 裸类名；不是**简单标识符**就返回 None（泛型/数组/值类型一律不要）。"""
    t = t.strip().rstrip('?')
    if '<' in t or '[' in t or ',' in t:
        return None
    t = t.split('.')[-1]
    return t if re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', t) else None


def element_class_of(type_text: str):
    """`Array`/`Map` 字段的**元素类名**（下钻用）；取不到返回 None。

    只认「元素本身就是个类」的情形：`List<BuildingDrawLayer>` → `BuildingDrawLayer`，
    `Dictionary<string, BuildingData>` → `BuildingData`（取**值**那一侧）。
    `List<string>` / `List<List<X>>` / `int[]` 都给 None —— 里面没有可下钻的类。
    """
    t = type_text.strip().rstrip('?')
    m = re.match(r'^(?:List|IList|IEnumerable|HashSet|ICollection)<(.*)>$', t)
    if m:
        parts = split_top_level(m.group(1))
        return bare_class(parts[0]) if len(parts) == 1 else None
    m = re.match(r'^(?:Dictionary|IDictionary)<(.*)>$', t)
    if m:
        parts = split_top_level(m.group(1))
        return bare_class(parts[1]) if len(parts) == 2 else None
    m = re.match(r'^([A-Za-z0-9_.]+)\[\]$', t)
    if m:
        return bare_class(m.group(1))
    return None


def element_type_of(asset_generic: str):
    """`Load<...>` 的泛型实参 → 元素类型的裸类名；取不到返回 None。"""
    g = asset_generic.strip()
    args = re.match(r'^(?:Dictionary|IDictionary)<(.+)>$', g)
    if args:
        parts = split_top_level(args.group(1))
        if len(parts) != 2:
            return None
        inner = parts[1].strip()
        # Dictionary<K, List<T>> 这类：元素就是 List，没有单一类名
        return strip_generic(inner) if not inner.startswith('List<') else None
    if g.startswith('List<'):
        return strip_generic(g)
    return strip_generic(g)


def root_kind_of(asset_generic: str):
    """`Load<...>` 的泛型实参 → **资产根**的容器种类（`Array` / `Map`）。

    <b>为什么要它</b>：新建一个资产时得知道顶层该是 JSON 数组还是对象 ——
    形状错了回包会直接失败。原先这件事由手抄的 `Merging/ArrayAssets.cs` 白名单承担，
    与这里的来源是同一份 `DataLoader.cs`，属于「同功能两处实现」。
    """
    g = asset_generic.strip()
    if g.startswith('List<') or re.match(r'^[A-Za-z0-9_.]+\[\]$', g):
        return 'Array'
    if re.match(r'^(?:Dictionary|IDictionary)<', g):
        return 'Map'
    return None


def parse_loader():
    """资产名 → (元素类名, 根的容器种类)。

    ⚠ **`DataLoader.cs` 里有两种调用形态**，两种都要收：
      ① `Load<T>(content, "Data\\X")` —— 走本文件的 Load 帮助方法；
      ② `content.Load<T>("Data\\X")` —— 直接调 ContentManager。
    只收 ① 会**静默漏掉 4 个资产**（实测：`Data/MakeoverOutfits`、`Data/Mannequins`、
    `Data/Powers`、`Data/Trinkets`）—— 是手抄的 `Merging/ArrayAssets.cs` 白名单
    把 `Data/MakeoverOutfits` 收着才暴露出来的。**手抄副本反过来抓出了生成器的漏**，
    这条经验记在这里：改成生成之后，手抄的那份要**留作测试**，不要直接删。
    """
    text = open(SRC, encoding='utf-8-sig', errors='replace').read()
    pattern = (r'Load<([^;]+?)>\(\s*content\s*,\s*"([^"]+)"\s*\)'
               r'|content\.Load<([^;]+?)>\(\s*"([^"]+)"\s*\)')
    out = {}
    for m in re.finditer(pattern, text):
        generic = (m.group(1) or m.group(3)).strip()
        asset = (m.group(2) or m.group(4)).replace('\\\\', '/')
        elem = element_type_of(generic)
        kind = root_kind_of(generic)
        if elem and kind and re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', elem):
            out[asset] = (elem, kind)
    return out


def collect_enum_names():
    """所有**枚举类型名**（`StardewValley.GameData.*` 里的 + 游戏本体 `StardewValley\\*.cs` 里的）。

    为什么要它：`EndSlideShow` 声明的是 `EndSlideShowBehavior`（枚举），包写了 `true`
    ⇒ 打包器 `Unexpected token Boolean when parsing enum` ⇒ **整份资产打不出包**
    （实测 `Data/Characters` 连它的 9 个语言变体）。要判"这个字段是枚举"
    只能看**声明**，不能看字段名或取值。
    """
    names = set()
    enum_re = re.compile(r'\benum\s+([A-Za-z_][A-Za-z0-9_]*)')
    for root in (GD, os.path.join(SRC, '..')):
        for dp, _, fs in os.walk(root):
            for f in fs:
                if not f.endswith('.cs'):
                    continue
                text = open(os.path.join(dp, f), encoding='utf-8-sig', errors='replace').read()
                names.update(enum_re.findall(text))
    return names


def parse_models():
    """→ (类名 → 字段表, 整数字段表, 枚举字段表)。只取 public 字段/属性。"""
    classes = {}
    integer_fields = {}
    enum_fields = {}
    bases = {}
    enums = collect_enum_names()
    field_re = re.compile(
        r'public\s+(?:readonly\s+)?([A-Za-z0-9_<>,\.\[\]\? ]+?)\s+([A-Za-z_][A-Za-z0-9_]*)'
        r'\s*(?:=|;|\{)')
    for dp, _, fs in os.walk(GD):
        for f in fs:
            if not f.endswith('.cs'):
                continue
            text = open(os.path.join(dp, f), encoding='utf-8-sig', errors='replace').read()
            for cm in re.finditer(
                    r'public\s+(?:sealed\s+)?(?:abstract\s+)?class\s+([A-Za-z_][A-Za-z0-9_]*)'
                    r'(?:\s*:\s*([A-Za-z_][A-Za-z0-9_<>,\s\.]*))?', text):
                name = cm.group(1)
                bases[name] = [strip_generic(b.strip().split('.')[-1])
                               for b in (cm.group(2) or '').split(',') if b.strip()]
                start = cm.end()
                end = text.find('\n}', start)
                body = text[start:end if end > 0 else len(text)]
                fields = {}
                ints = set()
                enum_fs = set()
                for fm in field_re.finditer(body):
                    ftype, fname = fm.group(1).strip(), fm.group(2)
                    if ftype in ('class', 'void', 'static', 'const', 'override', 'virtual'):
                        continue
                    kind = container_of(ftype)
                    # Struct 要带**结构类型名**（Vector2/…）：「"0, -32" 拆成哪几个分量」
                    # 只有类型说了算 —— 按逗号个数猜是**推断**，而这里是**声明的事实**。
                    el = strip_generic(ftype) if kind == 'Struct' else (element_class_of(ftype) or '')
                    fields[fname] = (kind, el)
                    # 标量里单独把**整数类型**挑出来（要用它判「整数值被写成了小数记号」）。
                    if kind == 'Scalar' and ftype.rstrip('?') in INTEGER_TYPES:
                        ints.add(fname)
                    # 枚举字段也单独挑出来：`true` 写进枚举位打包器直接失败
                    # （`Unexpected token Boolean when parsing enum`）⇒ 整份资产报废。
                    if kind == 'Scalar' and ftype.rstrip('?') in enums:
                        enum_fs.add(fname)
                if fields:
                    classes[name] = fields
                if ints:
                    integer_fields[name] = ints
                if enum_fs:
                    enum_fields[name] = enum_fs

    # ★ **继承来的字段也是游戏的字段**。`FruitTreeFruitData : GenericSpawnItemDataWithCondition`
    #   就是活例：`Condition` 在基类上声明，子类注释里还专门指向它。
    #   不合并基类 ⇒ `conditionPlacement` 自检会把「`Fruit[].Condition` 写在游戏不读的位置」
    #   报成一堆**假阳性**（实测每个包 19 处）。
    def own_and_inherited(cls: str, seen: set) -> dict:
        """本类 + 全部基类的字段（递归；`seen` 防环）。"""
        out = dict(classes.get(cls, {}))
        for base in bases.get(cls, []):
            if base in seen:
                continue
            seen.add(base)
            for field, ref in own_and_inherited(base, seen).items():
                out.setdefault(field, ref)
        return out

    def int_or_enum(cls: str, table: dict, seen: set) -> set:
        out = set(table.get(cls, ()))
        for base in bases.get(cls, []):
            if base in seen:
                continue
            seen.add(base)
            out |= int_or_enum(base, table, seen)
        return out

    for cls in list(classes):
        for field, ref in own_and_inherited(cls, {cls}).items():
            classes[cls].setdefault(field, ref)
    for cls in list(classes):
        merged_ints = int_or_enum(cls, integer_fields, {cls})
        if merged_ints:
            integer_fields[cls] = merged_ints
        merged_enums = int_or_enum(cls, enum_fields, {cls})
        if merged_enums:
            enum_fields[cls] = merged_enums
    return classes, integer_fields, enum_fields


# 校验器下钻的最大层数。生成器要**多收一层**，免得边界上的类漏掉。
DEPTH = 6


def reachable(elem_classes, classes):
    """从资产元素类出发，沿元素类名走 DEPTH 层，收下够得着的类名。"""
    seen, frontier = set(), list(elem_classes)
    for _ in range(DEPTH + 1):
        nxt = []
        for c in frontier:
            if c in seen:
                continue
            seen.add(c)
            nxt += [el for _, el in classes.get(c, {}).values() if el]
        frontier = nxt
    return {c for c in seen if c in classes}


def interesting_fields(fields):
    """只留非 Scalar 的字段：标量没有容器形状可查，留着只是噪音。"""
    return {k: v for k, v in sorted(fields.items()) if v[0] != 'Scalar'}


def generate():
    assets, (classes, integer_fields, enum_fields) = parse_loader(), parse_models()
    keep = reachable([e for e, _ in assets.values()], classes)

    rows = []
    for asset in sorted(assets):
        elem = assets[asset][0]
        if interesting_fields(classes.get(elem, {})):
            rows.append((asset, elem))

    lines = [HEADER]
    lines.append('/// <summary>\n')
    lines.append('/// 游戏的数据模型（从源码生成）：**资产 → 元素类 / 根形状**，以及**类 → 容器型字段**。\n')
    lines.append('/// <para>\n')
    lines.append('/// ★ 分成几张表是为了**能下钻**：只按资产列表会止步于「资产元素的一层字段」，\n')
    lines.append('/// 查不到 <c>DrawLayers[].DrawPosition</c> 这类嵌套层的问题。\n')
    lines.append('/// </para>\n')
    lines.append('/// </summary>\n')
    lines.append('public static class GameDataSchema\n{\n')

    lines.append('    /// <summary>\n')
    lines.append('    /// 资产名 → <b>元素类名</b>（<c>DataLoader.cs</c> 的 <c>Load&lt;T&gt;</c> 泛型实参）。\n')
    lines.append('    /// </summary>\n')
    lines.append('    public static readonly Dictionary<string, string> AssetElement = new()\n    {\n')
    for asset, elem in rows:
        lines.append(f'        ["{asset}"] = "{elem}",\n')
    lines.append('    };\n\n')

    lines.append('    /// <summary>\n')
    lines.append('    /// 资产名 → <b>根容器</b>（<c>Array</c> = <c>Load&lt;List&lt;T&gt;&gt;</c>，<c>Map</c> = <c>Load&lt;Dictionary&lt;K,V&gt;&gt;</c>）。\n')
    lines.append('    /// <para>\n')
    lines.append('    /// <b>用来干什么</b>：新建一个资产时顶层该产出 JSON 数组还是对象 ——\n')
    lines.append('    /// 形状错了回包会**直接失败**。这份事实原先由手抄的 <c>Merging/ArrayAssets.cs</c> 承担，\n')
    lines.append('    /// 与这里是同一份 <c>DataLoader.cs</c> 的两个副本，已改为只读本表。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// </summary>\n')
    lines.append('    public static readonly Dictionary<string, FieldKind> AssetRootKind = new(StringComparer.OrdinalIgnoreCase)\n    {\n')
    for asset in sorted(assets):
        lines.append(f'        ["{asset}"] = FieldKind.{assets[asset][1]},\n')
    lines.append('    };\n\n')

    lines.append('    /// <summary>\n')
    lines.append('    /// 类名 → 字段 → 类型引用。只收容器型字段（标量没有形状可查）。\n')
    lines.append('    /// <para>\n')
    lines.append('    /// 字段名<b>不区分大小写</b>：打包器与游戏都按大小写不敏感地匹配字段名\n')
    lines.append('    /// （实测：`Data/WorldMap` 里把 `Tooltips` 写成 `ToolTips`，打包器照认并按其真类型\n')
    lines.append('    /// `List&lt;WorldMapTooltipData&gt;` 校验），所以查表也得照做，否则同一个字段\n')
    lines.append('    /// 在「认得出」与「认不出」之间摇摆。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// </summary>\n')
    lines.append('    public static readonly Dictionary<string, Dictionary<string, FieldRef>> Types =\n')
    lines.append('        new(StringComparer.Ordinal)\n    {\n')
    for name in sorted(keep):
        fields = interesting_fields(classes[name])
        if not fields:
            continue
        lines.append(f'        ["{name}"] = new(StringComparer.OrdinalIgnoreCase)\n        {{\n')
        for k, (kind, el) in fields.items():
            lines.append(f'            ["{k}"] = new(FieldKind.{kind}, "{el}"),\n')
        lines.append('        },\n')
    lines.append('    };\n')

    lines.append('\n')
    lines.append('    /// <summary>\n')
    lines.append('    /// 类名 → **声明为整数类型**的字段名（只收够得着的类）。\n')
    lines.append('    /// <para>\n')
    lines.append('    /// <b>用来干什么</b>：整数值不能写成小数记号。CP 那边可以写 `0.0`（游戏自己的\n')
    lines.append('    /// 转换器认），XNB 树这边打包器直接报 `Input string \'0.0\' is not a valid integer`\n')
    lines.append('    /// ⇒ 该资产**打不出包**（实测 `Data/Objects` 连它的 5 个语言变体）。\n')
    lines.append('    /// `0.0` 与 `0` 是**同一个数**，所以按这个表改写**不改变取值**；\n')
    lines.append('    /// 带小数部分的（如 `Precision: 0.5`）**不改成整数**（那是改值），\n')
    lines.append('    /// 而是**删掉那个字段并报出来** —— 见 `ValueDialectCoercion` 的第三条规则。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// <para>\n')
    lines.append('    /// 判据是**声明事实**（`D:\\sdv_gd` 里那些 `public int X;`），不是拿数据反推的。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// </summary>\n')
    lines.append('    public static readonly Dictionary<string, string[]> IntegerFields =\n')
    lines.append('        new(StringComparer.Ordinal)\n    {\n')
    for name in sorted(keep):
        names = sorted(integer_fields.get(name, ()))
        if not names:
            continue
        body = ', '.join(f'"{n}"' for n in names)
        lines.append(f'        ["{name}"] = new[] {{ {body} }},\n')
    lines.append('    };\n')

    lines.append('\n')
    lines.append('    /// <summary>\n')
    lines.append('    /// 类名 → **声明为枚举类型**的字段名（只收够得着的类）。\n')
    lines.append('    /// <para>\n')
    lines.append('    /// <b>用来干什么</b>：包把 <c>true</c>/<c>false</c> 写进枚举字段时，打包器直接报\n')
    lines.append('    /// <c>Unexpected token Boolean when parsing enum</c> ⇒ **整份资产打不出包**\n')
    lines.append('    /// （实测 `Data/Characters` 的 `Antiunn.EndSlideShow` 连它的 9 个语言变体一起报废 ——\n')
    lines.append('    /// 而那棵树里有 221 个 mod 新增的 NPC 定义，覆盖式装机下会整份退回原版）。\n')
    lines.append('    /// 这种值**改不动**（`true` 到底该当哪个枚举成员，只有作者知道）⇒\n')
    lines.append('    /// 写入侧的做法是**删掉那个字段并报出来**（见 `ValueDialectCoercion`），\n')
    lines.append('    /// 让其余条目照常打包。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// <para>\n')
    lines.append('    /// 判据是**声明事实**（字段类型是 `D:\\sdv_gd` 或游戏本体里声明过的 `enum`），\n')
    lines.append('    /// 不是拿字段名或取值反推的。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// </summary>\n')
    lines.append('    public static readonly Dictionary<string, string[]> EnumFields =\n')
    lines.append('        new(StringComparer.Ordinal)\n    {\n')
    for name in sorted(keep):
        names = sorted(enum_fields.get(name, ()))
        if not names:
            continue
        body = ', '.join(f'"{n}"' for n in names)
        lines.append(f'        ["{name}"] = new[] {{ {body} }},\n')
    lines.append('    };\n')

    lines.append('\n')
    lines.append('    /// <summary>\n')
    lines.append('    /// 类名 → **全部字段名**（含标量与继承来的；只收够得着的类）。\n')
    lines.append('    /// <para>\n')
    lines.append('    /// <b>用来干什么</b>：判「这个字段游戏到底读不读」。`Types` 那张表只收**容器型**字段\n')
    lines.append('    /// （标量没有形状可查），而 `conditionPlacement` 自检要回答的是\n')
    lines.append('    /// 「`Fruit[]/Condition` 这种位置上**模型里有这个字段吗**」：\n')
    lines.append('    /// 有 ⇒ 游戏会反序列化它（**合法**，哪怕原版自己不用）；\n')
    lines.append('    /// 没有 ⇒ 游戏**整段忽略**（实测 `WorldMap` 的 `MapAreas[]/KnownCondition` —— 包的 bug）。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// <para>\n')
    lines.append('    /// ⚠ <b>继承的字段也要算</b>：`FruitTreeFruitData : GenericSpawnItemDataWithCondition`\n')
    lines.append('    /// 的 `Condition` 就声明在基类上（子类注释还专门指向它）。不合并基类的话，\n')
    lines.append('    /// 自检会把 `Fruit[].Condition` 报成一堆假阳性（实测每个包 19 处）。\n')
    lines.append('    /// </para>\n')
    lines.append('    /// </summary>\n')
    lines.append('    public static readonly Dictionary<string, HashSet<string>> KnownFields =\n')
    lines.append('        new(StringComparer.Ordinal)\n    {\n')
