#!/usr/bin/env python3
"""从**游戏数据**生成 `WalletItems`：CP 的钱包物品名 → 等价 GSQ。

## 为什么不是「GSQ 里没有钱包关键字」就完事

`HasWalletItem` 曾被判成「GSQ 没有等价关键字」。**逐层挖下去之后发现它完全可以翻译**：

1. **`D:\\sdv_tree\\Data\\Powers.json`（原版数据）里每个 power 都带 `UnlockedCondition`，
   那本身就是一句 GSQ** —— 而钱包物品就是 power。这是最权威的一份，
   因为它是**游戏自己的数据**，不是我推的。
2. 交叉核对 `D:\\sdv_src\\StardewValley\\Farmer.cs` 里那几个属性：
   `hasRustyKey` = `Game1.MasterPlayer.mailReceived.Contains("HasRustyKey")`（`:1388-1400`），
   与 `Powers.json` 的 `RustyKey` → `PLAYER_HAS_MAIL Host HasRustyKey` **完全一致**。
   ⚠ 注意宿主不同：`RustyKey`/`SkullKey`/`DwarvishTranslationGuide` 读的是
   **`Game1.MasterPlayer`**（主机），其余读实例字段 `mailReceived`（当前玩家）——
   `Powers.json` 里 `Host` / `Current` 的差别正是这个，别自己改成一律 `Current`。
3. **CP 的名集**从 `ContentPatcher.dll` 提出来：7 个属性 getter
   （`get_hasClubCard` / `get_hasDarkTalisman` / `get_hasMagicInk` / `get_hasRustyKey` /
   `get_hasSkullKey` / `get_hasSpecialCharm` / `get_hasMagnifyingGlass`）
   ＋ 4 个字面量（`BearsKnowledge` / `KeyToTheTown` / `SpringOnionMastery` / `DwarvishTranslationGuide`）。
4. ⚠ **唯一的改名**：CP 叫 `BearsKnowledge`，`Powers.json` 里的 id 叫 `BearPaw`。
   佐证：CP 的 DLL 里**同时**有 `BearsKnowledge` 与事件 ID `2120303`，
   而 `Powers.json` 里 `BearPaw` 的 `UnlockedCondition` 正是 `PLAYER_HAS_SEEN_EVENT Current 2120303`
   （`SpringOnionMastery` ↔ `3910979` 同理）。**这是推断，不是读到 CP 的源码**，故在生成物里标注。

## 用法

    python tools/gen-wallet-items.py            # 生成并写回仓库
    python tools/gen-wallet-items.py --check    # 只校验是否与仓库里的一致
"""
import json
import os
import sys

POWERS = r'D:\sdv_tree\Data\Powers.json'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   '..', 'src', 'SdvCpTool.Core', 'Validating', 'WalletItems.cs')

# CP 的名集（证据见文件头）。值是 `Powers.json` 里的 power id；同名时可直接省掉。
# ⚠ 只收**从 CP 的 DLL 里确实读到过**的名字 —— 宁可少收，也不要凭「看起来像」放行一个
#   CP 根本不认的值（放行了就会把一个 CP 本会拒绝的条件翻译出去）。
CP_NAMES = {
    'RustyKey': 'RustyKey',
    'SkullKey': 'SkullKey',
    'ClubCard': 'ClubCard',
    'SpecialCharm': 'SpecialCharm',
    'MagicInk': 'MagicInk',
    'DarkTalisman': 'DarkTalisman',
    'MagnifyingGlass': 'MagnifyingGlass',
    'KeyToTheTown': 'KeyToTheTown',
    'DwarvishTranslationGuide': 'DwarvishTranslationGuide',
    'SpringOnionMastery': 'SpringOnionMastery',
    'BearsKnowledge': 'BearPaw',        # ← CP 与游戏 id 的唯一改名（推断，见文件头第 4 条）
}

HEADER = '''// <auto-generated>
//   由 tools/gen-wallet-items.py 生成 —— **不要手改**。
//   数据来源：D:\\sdv_tree\\Data\\Powers.json（原版数据，每个 power 自带 UnlockedCondition）
//            交叉核对 D:\\sdv_src\\StardewValley\\Farmer.cs 的钱包属性实现
//   重新生成：python tools/gen-wallet-items.py
// </auto-generated>

namespace SdvCpTool.Core.Validating;

'''


def generate():
    powers = json.load(open(POWERS, encoding='utf-8-sig'))

    rows = []
    missing = []
    for cp_name, power_id in sorted(CP_NAMES.items()):
        entry = powers.get(power_id)
        if not entry:
            missing.append(f'{cp_name} → {power_id}（Powers.json 里没有这个 id）')
            continue
        cond = (entry.get('UnlockedCondition') or '').strip()
        if not cond:
            missing.append(f'{cp_name} → {power_id}（UnlockedCondition 是空的）')
            continue
        rows.append((cp_name, power_id, cond))

    if missing:
        raise SystemExit('生成失败，先修这些：\n  ' + '\n  '.join(missing))

    lines = [HEADER]
    lines.append('/// <summary>\n')
    lines.append('/// CP 的 <c>HasWalletItem</c> 名 → <b>等价 GSQ</b>。\n')
    lines.append('/// <para>\n')
    lines.append('/// <b>为什么这张表是权威的</b>：原版数据 <c>Data/Powers.json</c> 里每个 power\n')
    lines.append('/// 自带 <c>UnlockedCondition</c>，那**本身就是一句 GSQ** —— 而钱包物品就是 power。\n')
    lines.append('/// 生成器直接取它，不自己发明条件。\n')
    lines.append('/// </para>\n')
    lines.append('/// <para>\n')
    lines.append('/// ⚠ <c>Host</c> / <c>Current</c> 的差别是**真实的**：<c>RustyKey</c>/<c>SkullKey</c>/\n')
    lines.append('/// <c>DwarvishTranslationGuide</c> 在 <c>Farmer.cs</c> 里读的是 <c>Game1.MasterPlayer</c>\n')
    lines.append('/// （主机），其余读实例字段 <c>mailReceived</c>（当前玩家）。**别改成一律 Current**。\n')
    lines.append('/// </para>\n')
    lines.append('/// <para>\n')
    lines.append('/// ⚠ <c>BearsKnowledge</c> → power id <c>BearPaw</c> 是**推断**：CP 的 DLL 里同时有\n')
    lines.append('/// <c>BearsKnowledge</c> 与事件 ID <c>2120303</c>，而 <c>Powers.json</c> 里\n')
    lines.append('/// <c>BearPaw</c> 的条件正是 <c>PLAYER_HAS_SEEN_EVENT Current 2120303</c>。没读到 CP 源码。\n')
    lines.append('/// </para>\n')
    lines.append('/// </summary>\n')
    lines.append('public static class WalletItems\n{\n')
    lines.append('    /// <summary>CP 名 → GSQ。</summary>\n')
    lines.append('    public static readonly Dictionary<string, string> Map = new(StringComparer.OrdinalIgnoreCase)\n    {\n')
    for cp_name, power_id, cond in rows:
        note = f'   // power: {power_id}' + ('（CP 与游戏 id 不同名，推断）' if cp_name != power_id else '')
        lines.append(f'        ["{cp_name}"] = "{cond}",{note}\n')
    lines.append('    };\n')
    lines.append('}\n')
    return ''.join(lines), len(rows)


def main():
    text, n = generate()
    check = '--check' in sys.argv
    path = os.path.normpath(OUT)
    if check:
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if current != text:
            print('与仓库里的不一致 —— 请重新生成', file=sys.stderr)
            sys.exit(1)
        print(f'一致（{n} 个钱包物品）')
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'写入 {path}：{n} 个钱包物品')


if __name__ == '__main__':
    main()
